#[tokio::test]
async fn pre_epoch_and_far_future_timestamps_decode() {
    // A `GD_WHEN` property before 1970 is a negative microsecond count, and a
    // far-future one exceeds 2^31 seconds. Both appear in real data (imported
    // birth dates, sentinel expiry values) and both break naive conversions.
    for tree in TREES {
        let parsed = parse_tree(tree).await;
        let values = by_property(&parsed.documents, "Values", "unindexed_note");

        for (id, expected_year) in [("raw:limits", "1969"), ("raw:coercions", "2286")] {
            let doc = values
                .get(id)
                .unwrap_or_else(|| panic!("{tree}: Values/{id} missing"));
            let when = doc
                .data
                .get("when")
                .unwrap_or_else(|| panic!("{tree}: {id} has no 'when' property"));
            let rendered = when
                .get("rfc3339")
                .and_then(Value::as_str)
                .unwrap_or_else(|| panic!("{tree}: {id} 'when' is not a tagged timestamp: {when}"));
            assert!(
                rendered.starts_with(expected_year),
                "{tree}: {id} 'when' should be in {expected_year}, got {rendered}"
            );
        }
    }
}

#[tokio::test]
async fn an_unindexed_raw_property_is_still_exported() {
    // Legacy exports carry unindexed properties in `EntityProto.raw_property`
    // (field 15), not `property` (field 14). A decoder that reads only field 14
    // drops them, and `excludeFromIndexes` is common on large text fields.
    let parsed = parse_tree("export-edge-onestore").await;
    let values = documents_of(&parsed.documents, "Values");
    assert_eq!(values.len(), 4, "all Values entities must be parsed");
    for doc in values {
        let note = doc.data.get("unindexed_note").and_then(Value::as_str);
        assert!(
            note.is_some_and(|text| text.starts_with("raw:")),
            "Values/{} lost its raw_property: {:?}",
            doc.id,
            doc.data.keys().collect::<Vec<_>>()
        );
    }
}

