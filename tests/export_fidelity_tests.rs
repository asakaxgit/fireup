#[tokio::test]
async fn a_three_level_ancestor_path_keeps_every_element() {
    // The base fixtures stop at two levels, so a decoder that reads only the
    // first and last path elements passes there and loses the middle here.
    for tree in TREES {
        let parsed = parse_tree(tree).await;
        let labelled = by_property(&parsed.documents, "Idents", "label");
        let deep = labelled
            .get("three-level-ancestor")
            .unwrap_or_else(|| panic!("{tree}: three-level-ancestor missing"));

        let key = deep.key.as_ref().expect("three-level key");
        let rendered: Vec<String> = key
            .path
            .iter()
            .map(|element| format!("{}:{}", element.kind, element.id.as_path_segment()))
            .collect();
        assert_eq!(
            rendered,
            vec!["Org:acme", "Team:42", "Idents:deep"],
            "{tree}: every ancestor element must survive"
        );
        assert_eq!(
            key.parent_encoded_path().as_deref(),
            Some(
                fireup::types::DatastoreKey {
                    namespace: String::new(),
                    path: key.path[..2].to_vec(),
                }
                .encoded_path()
                .as_str()
            ),
            "{tree}: the parent link must point at the immediate parent"
        );
    }
}

