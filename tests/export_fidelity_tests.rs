//! Export-fidelity regression suite for the `export-edge-*` fixture trees.
//!
//! `tests/real_export_validation.rs` covers the happy path: one `output-0` per
//! kind, the default namespace, well-behaved values. This file covers the parts
//! of a real managed export that the happy path does not reach, and where a
//! regression is *silent* — fireup exits 0 and the migrated database is simply
//! missing or merging rows:
//!
//! | Area | Fixture | Regression it catches |
//! | --- | --- | --- |
//! | output shards | `kind_Shards/output-{0,1,2,10}` | reading only the first shard; sorting shards as text |
//! | fragment framing | `kind_Fragments` | mishandling `MIDDLE`, or a record that exactly fills a block |
//! | key identity | `kind_Idents` | merging an int64 id with a same-looking string name |
//! | namespaces | `namespace_tenant-{a,b}/kind_Scoped` | ignoring the partition, so two tenants' rows collide |
//! | numeric limits | `kind_Values` | int64 saturation, non-finite doubles, pre-epoch timestamps |
//! | property names | `kind_Awkward` | identifier collisions once PostgreSQL truncates to 63 bytes |
//!
//! Fixtures are generated by `tests/fixtures/generate_edge_export.py` and are
//! independently verified here by `tests/support/export_log_reader.rs`, so a
//! failure in this file is a fireup finding, not a fixture artifact.
//!
//! The PostgreSQL-backed half of this coverage (does the generated DDL actually
//! load, do the rows actually arrive) lives in `tests/ddl_postgres_load_tests.rs`
//! and `tests/postgres_import_tests.rs`, which skip without a database.

use std::collections::{HashMap, HashSet};

use fireup::leveldb_parser::parser::{FirestoreDocumentParser, ParseResult};
use fireup::monitoring::{initialize_monitoring, MonitoringConfig};
use fireup::schema_analyzer::{DocumentStructureAnalyzer, NormalizationEngine};
use fireup::types::{
    datastore_type_tag, DatastoreKeyId, FirestoreDocument, NormalizedSchema,
    DATASTORE_TYPE_DOUBLE, MAX_IDENTIFIER_BYTES,
};
use serde_json::Value;

#[path = "support/export_log_reader.rs"]
mod export_log_reader;

use export_log_reader::{
    fixtures_dir, kind_output, kind_shard, partition_shard, read_log, RECORD_FIRST, RECORD_FULL,
    RECORD_LAST, RECORD_MIDDLE, BLOCK_SIZE, HEADER_SIZE,
};

/// Both trees carry the same logical dataset in the two payload encodings, so a
/// failure in both is a framing bug and a failure in one is a payload bug.
const TREES: [&str; 2] = ["export-edge-onestore", "export-edge-v1"];

/// Every entity the generator writes, across all kinds and partitions.
const EXPECTED_ENTITIES: usize = 25;

fn init_monitoring() {
    initialize_monitoring(MonitoringConfig::default());
}

async fn parse(path: std::path::PathBuf) -> ParseResult {
    init_monitoring();
    let parser = FirestoreDocumentParser::new(path.to_string_lossy().to_string());
    parser
        .parse_documents()
        .await
        .unwrap_or_else(|e| panic!("parse {}: {e}", path.display()))
}

async fn parse_tree(tree: &str) -> ParseResult {
    parse(fixtures_dir().join(tree)).await
}

/// Documents of one kind, indexed by the value of a uniquely-valued property.
///
/// Keying on a property rather than on the document id is deliberate: several
/// `Idents` fixtures have ids that render identically, which is the bug under
/// test, so an id-keyed map would hide it.
fn by_property<'a>(
    documents: &'a [FirestoreDocument],
    collection: &str,
    property: &str,
) -> HashMap<String, &'a FirestoreDocument> {
    documents
        .iter()
        .filter(|doc| doc.collection == collection)
        .map(|doc| {
            let value = doc
                .data
                .get(property)
                .unwrap_or_else(|| {
                    panic!("{}/{} has no '{property}' property", doc.collection, doc.id)
                })
                .as_str()
                .unwrap_or_else(|| panic!("{}/{} '{property}' is not a string", doc.collection, doc.id))
                .to_string();
            (value, doc)
        })
        .collect()
}

fn documents_of<'a>(documents: &'a [FirestoreDocument], collection: &str) -> Vec<&'a FirestoreDocument> {
    documents
        .iter()
        .filter(|doc| doc.collection == collection)
        .collect()
}

async fn normalized_schema(tree: &str) -> NormalizedSchema {
    let parsed = parse_tree(tree).await;
    let analysis = DocumentStructureAnalyzer::new()
        .analyze_documents(&parsed.documents)
        .await
        .expect("analyze documents");
    NormalizationEngine::new()
        .normalize_schema(&analysis)
        .expect("normalize schema")
}

