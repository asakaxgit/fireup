#[tokio::test]
async fn int64_limits_survive_without_saturating() {
    // `i64::MAX`/`i64::MIN` go through a 10-byte varint and, in the legacy
    // payload, through a signed reinterpretation. Anything that routes them via
    // f64 or i32 loses precision or wraps.
    for tree in TREES {
        let parsed = parse_tree(tree).await;
        let values = by_property(&parsed.documents, "Values", "unindexed_note");
        let limits = values
            .get("raw:limits")
            .unwrap_or_else(|| panic!("{tree}: Values/limits missing"));

        assert_eq!(
            limits.data.get("big").and_then(Value::as_i64),
            Some(i64::MAX),
            "{tree}: i64::MAX must round trip exactly"
        );
        assert_eq!(
            limits.data.get("small").and_then(Value::as_i64),
            Some(i64::MIN),
            "{tree}: i64::MIN must round trip exactly"
        );
    }
}

#[tokio::test]
async fn non_finite_doubles_are_not_silently_dropped() {
    // Datastore stores NaN and ±Infinity in a double property, and PostgreSQL's
    // `double precision` can hold all three. Turning them into NULL is silent
    // data loss, and failing the whole parse aborts an otherwise fine import —
    // both decoders must agree on one defined, non-destructive outcome.
    for tree in TREES {
        let parsed = parse_tree(tree).await;
        let values = by_property(&parsed.documents, "Values", "unindexed_note");

        for (id, expected) in [
            ("raw:limits", "NaN"),
            ("raw:coercions", "Infinity"),
            ("raw:infinities", "-Infinity"),
            ("raw:negative-infinity", "NaN"),
        ] {
            let doc = values.get(id).unwrap_or_else(|| {
                panic!("{tree}: Values/{id} missing — a non-finite double must not abort the parse")
            });
            let ratio = doc
                .data
                .get("ratio")
                .unwrap_or_else(|| panic!("{tree}: {id} has no 'ratio' property"));
            assert!(
                !ratio.is_null(),
                "{tree}: {id} 'ratio' became null, losing the {expected} the export carried"
            );
            assert_eq!(
                datastore_type_tag(ratio),
                Some(DATASTORE_TYPE_DOUBLE),
                "{tree}: {id} 'ratio' must be a tagged double, got {ratio}"
            );
            assert_eq!(
                ratio.get("literal").and_then(Value::as_str),
                Some(expected),
                "{tree}: {id} 'ratio' literal"
            );
        }
    }
}

