#[tokio::test]
async fn namespaced_partitions_are_discovered_and_kept_apart() {
    // `Scoped/shared-name` exists in both tenant-a and tenant-b. They are two
    // entities, and the generated key path has to say so or one tenant's row
    // overwrites the other's on import.
    for tree in TREES {
        let parsed = parse_tree(tree).await;
        let scoped = documents_of(&parsed.documents, "Scoped");
        assert_eq!(
            scoped.len(),
            4,
            "{tree}: expected 2 entities in each of 2 namespaces, got {}",
            scoped.len()
        );

        let namespaces: HashSet<&str> = scoped
            .iter()
            .map(|doc| {
                doc.key
                    .as_ref()
                    .unwrap_or_else(|| panic!("{tree}: Scoped/{} lost its key", doc.id))
                    .namespace
                    .as_str()
            })
            .collect();
        assert_eq!(
            namespaces,
            HashSet::from(["tenant-a", "tenant-b"]),
            "{tree}: namespaces must survive parsing"
        );

        let paths: HashSet<String> = scoped
            .iter()
            .map(|doc| doc.key.as_ref().unwrap().encoded_path())
            .collect();
        assert_eq!(
            paths.len(),
            4,
            "{tree}: namespaced keys must not collide; got {paths:?}"
        );
    }
}

// ---------------------------------------------------------------------------
// Key identity — an int64 id and a string name are different entities
// ---------------------------------------------------------------------------

#[tokio::test]
async fn a_numeric_key_id_and_a_matching_string_name_stay_distinct() {
    // Datastore's `Idents/id:1001` and `Idents/name:"1001"` are two entities.
    // Both render as `Idents/1001` in a human-readable path, so anything that
    // keys rows on that text merges them and loses one entity outright.
    for tree in TREES {
        let parsed = parse_tree(tree).await;
        let labelled = by_property(&parsed.documents, "Idents", "label");

        let numeric = labelled
            .get("numeric-id-1001")
            .unwrap_or_else(|| panic!("{tree}: numeric-id-1001 missing"));
        let named = labelled
            .get("string-name-1001")
            .unwrap_or_else(|| panic!("{tree}: string-name-1001 missing"));

        assert_eq!(
            numeric.key.as_ref().and_then(|k| k.path.last()).map(|e| &e.id),
            Some(&DatastoreKeyId::Id(1001)),
            "{tree}: the int64 id must decode as an id, not a name"
        );
        assert_eq!(
            named.key.as_ref().and_then(|k| k.path.last()).map(|e| &e.id),
            Some(&DatastoreKeyId::Name("1001".to_string())),
            "{tree}: the string name must decode as a name, not an id"
        );

        let numeric_path = numeric.key.as_ref().unwrap().encoded_path();
        let named_path = named.key.as_ref().unwrap().encoded_path();
        assert_ne!(
            numeric_path, named_path,
            "{tree}: an int64 id and a string name must not share a key path \
             — they are distinct entities and `key_path` is the primary key"
        );
    }
}

#[tokio::test]
async fn a_key_name_containing_slashes_does_not_forge_an_ancestor_path() {
    // `Idents` with the name `a/Idents/9` renders as `Idents/a/Idents/9`, which
    // is exactly what a two-level ancestor path renders as. Without escaping,
    // a name can impersonate another entity's key.
    for tree in TREES {
        let parsed = parse_tree(tree).await;
        let labelled = by_property(&parsed.documents, "Idents", "label");
        let slashed = labelled
            .get("slash-in-name")
            .unwrap_or_else(|| panic!("{tree}: slash-in-name missing"));

        let key = slashed.key.as_ref().expect("slash-in-name key");
        assert_eq!(key.path.len(), 1, "{tree}: the name is not an ancestor path");
        assert_eq!(
            key.path[0].id,
            DatastoreKeyId::Name("a/Idents/9".to_string()),
            "{tree}: the slashes belong to the name"
        );

        let encoded = key.encoded_path();
        let decoy = fireup::types::DatastoreKey {
            namespace: String::new(),
            path: vec![
                fireup::types::DatastoreKeyPathElement {
                    kind: "Idents".to_string(),
                    id: DatastoreKeyId::Name("a".to_string()),
                },
                fireup::types::DatastoreKeyPathElement {
                    kind: "Idents".to_string(),
                    id: DatastoreKeyId::Id(9),
                },
            ],
        };
        assert_ne!(
            encoded,
            decoy.encoded_path(),
            "{tree}: a key name with slashes must not encode to another key's path"
        );
    }
}

