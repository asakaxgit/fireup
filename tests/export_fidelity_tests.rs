// Output shards — every shard of every kind must be read
// ---------------------------------------------------------------------------

#[tokio::test]
async fn every_output_shard_of_a_kind_is_read() {
    // A kind sharded across output-0..output-N is the normal case for any
    // export big enough to matter. Stopping at output-0 loses 4 of these 6
    // entities and still exits 0.
    for tree in TREES {
        let parsed = parse_tree(tree).await;
        let shards = documents_of(&parsed.documents, "Shards");
        assert_eq!(shards.len(), 6, "{tree}: expected all 6 Shards entities");

        let mut sequences: Vec<i64> = shards
            .iter()
            .map(|doc| {
                doc.data
                    .get("sequence")
                    .and_then(Value::as_i64)
                    .unwrap_or_else(|| panic!("{tree}: Shards/{} has no sequence", doc.id))
            })
            .collect();
        sequences.sort_unstable();
        assert_eq!(
            sequences,
            (1..=6).collect::<Vec<i64>>(),
            "{tree}: every shard's entities must arrive exactly once"
        );
    }
}

#[tokio::test]
async fn a_two_digit_output_shard_is_not_skipped() {
    // `output-10` sorts before `output-2` as text. A reader that globs and
    // sorts lexically reads the shards out of order; one that parses the shard
    // number wrong drops the file entirely.
    for tree in TREES {
        let parsed = parse_tree(tree).await;
        let shards = documents_of(&parsed.documents, "Shards");
        let from_shard_10: Vec<&str> = shards
            .iter()
            .filter(|doc| doc.data.get("shard").and_then(Value::as_i64) == Some(10))
            .map(|doc| doc.id.as_str())
            .collect();
        assert_eq!(
            from_shard_10,
            vec!["s10a"],
            "{tree}: output-10's entity must be read exactly once"
        );
    }
}

