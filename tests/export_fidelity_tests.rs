#[test]
fn edge_fixture_layout_is_present() {
    for tree in TREES {
        let root = fixtures_dir().join(tree);
        assert!(root.is_dir(), "missing fixture tree {}", root.display());

        let overall = std::fs::read_dir(&root)
            .expect("read fixture root")
            .filter_map(Result::ok)
            .filter(|entry| {
                entry
                    .file_name()
                    .to_string_lossy()
                    .ends_with(".overall_export_metadata")
            })
            .count();
        assert_eq!(overall, 1, "{tree}: expected one .overall_export_metadata");

        // A kind sharded over several output files, including a two-digit shard.
        for shard in [0, 1, 2, 10] {
            assert!(
                kind_shard(tree, "Shards", shard).is_file(),
                "{tree}: missing kind_Shards/output-{shard}"
            );
        }

        // Non-default namespaces use `namespace_<ns>/`, not `all_namespaces/`.
        for namespace in ["tenant-a", "tenant-b"] {
            let partition = format!("namespace_{namespace}");
            assert!(
                partition_shard(tree, &partition, "Scoped", 0).is_file(),
                "{tree}: missing {partition}/kind_Scoped/output-0"
            );
            assert!(
                fixtures_dir()
                    .join(tree)
                    .join(&partition)
                    .join("kind_Scoped")
                    .join(format!("{partition}_kind_Scoped.export_metadata"))
                    .is_file(),
                "{tree}: missing {partition} per-kind .export_metadata"
            );
        }
    }
}

#[test]
fn fragment_fixture_emits_first_middle_and_last() {
    // The base fixtures' largest record spans two blocks, so it only ever
    // produces FIRST/LAST. A record spanning three blocks is the only way to
    // exercise MIDDLE, and a reader that mishandles MIDDLE silently truncates
    // the reassembled payload.
    for tree in TREES {
        let log = read_log(&kind_output(tree, "Fragments"));
        for record_type in [RECORD_FULL, RECORD_FIRST, RECORD_MIDDLE, RECORD_LAST] {
            assert!(
                log.has_record_type(record_type),
                "{tree}: kind_Fragments has no record type {record_type}; types = {:?}",
                log.record_types()
            );
        }
        assert_eq!(log.records.len(), 3, "{tree}: kind_Fragments record count");
    }
}

#[test]
fn fragment_fixture_has_a_record_that_exactly_fills_a_block() {
    // A body of exactly `BLOCK_SIZE - HEADER_SIZE` leaves zero slack, so the
    // next record starts at offset 0 of the next block with no zero padding
    // between them. An off-by-one in the remaining-room calculation shows up
    // here and nowhere else.
    for tree in TREES {
        let log = read_log(&kind_output(tree, "Fragments"));
        let exact = log
            .fragments
            .iter()
            .find(|f| f.payload_len == BLOCK_SIZE - HEADER_SIZE)
            .unwrap_or_else(|| {
                panic!(
                    "{tree}: no record body of exactly {} bytes; lengths = {:?}",
                    BLOCK_SIZE - HEADER_SIZE,
                    log.fragments.iter().map(|f| f.payload_len).collect::<Vec<_>>()
                )
            });
        assert_eq!(exact.offset, 0, "{tree}: exact-fill record must start a block");

        let next = log
            .fragments
            .iter()
            .find(|f| f.block == exact.block + 1)
            .expect("a record after the exactly-filled block");
        assert_eq!(
            next.offset, 0,
            "{tree}: the record after an exact fill must start at offset 0"
        );
    }
}

